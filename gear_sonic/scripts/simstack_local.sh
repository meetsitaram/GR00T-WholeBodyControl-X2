# Launch verdict — wait until the deploy actually reaches CONTROL (or
# dies) instead of printing "ready" over a corpse. A silent argparse
# death and a viewer-stall E-STOP both hid behind "ready" (2026-08-29).
# ------------------------------------------------------------------
echo "  waiting for deploy verdict (CONTROL vs FATAL, up to 60 s) ..."
VERDICT=""
for _ in $(seq 1 60); do
  if grep -qE "\[FATAL\]|-> SAFE_HOLD" "$S/logs/deploy.log" 2>/dev/null; then
    VERDICT=fatal; break
  fi
  if grep -q "Autostart elapsed" "$S/logs/deploy.log" 2>/dev/null; then
    VERDICT=control; break
  fi
  if ! kill -0 "$(pgrep -f 'deploy_x2.sh sim' | head -1)" 2>/dev/null \
     && ! docker ps -q --filter name=x2sim | grep -q .; then
    VERDICT=dead; break
  fi
  sleep 1
done
case "$VERDICT" in
  control)
    # Deploy is up — now verify the PAD CHAIN armed off its x2_debug echo.
    # The kplanner lazily waits (silent, by design) for the deploy's debug
    # stream; a wiring break leaves it waiting FOREVER while the watchdog
    # holds the stand — pad dead with zero errors anywhere (bit the
    # operator 2026-08-29 after the 5657->5659 debug-port move).
    KP_ARMED=""
    for _ in $(seq 1 20); do
      if grep -qE "rebase ARMED|planner active" "$S/logs/kplanner.log" 2>/dev/null; then
        KP_ARMED=1; break
      fi
      sleep 1
    done
    if [[ -z "$KP_ARMED" ]]; then
      echo "  VERDICT: DEPLOY UP but KPLANNER NEVER ARMED — pad control is DEAD."
      echo "  (kplanner is not receiving the deploy's x2_debug echo — port wiring?)"
      tail -3 "$S/logs/kplanner.log" | sed 's/^/    | /'
      exit 1
    fi
    echo "  VERDICT: deploy in CONTROL + kplanner ARMED — stack is UP, pad live."
    # Host-side mirror viewer (renders from robot_pose/x2_debug telemetry;
    # read-only, cannot stall the sim). The in-container --sim-viewer is
    # GONE: no NV-GLX in docker, and its GL stall E-STOPPED the deploy.
    if [[ "${SIM_VIEWER_ARGS-viewer}" != "" && "${SIMSTACK_NO_VIEWER:-0}" != "1" && -f "$REPO/gear_sonic/scripts/sim_mirror_viewer.py" ]]; then
